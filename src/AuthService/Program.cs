using AuthService.Data;
using AuthService.Endpoints;
using AuthService.Extensions;
var builder = WebApplication.CreateBuilder(args);
builder.Services.AddAuthService(builder.Configuration);
var app = builder.Build();
app.UseSwagger();
app.UseSwaggerUI(o => { o.SwaggerEndpoint("/swagger/v1/swagger.json", "WAEC Authentication Service API V1"); o.RoutePrefix = "swagger"; });
app.UseAuthentication();
app.UseAuthorization();
await DatabaseInitializer.InitializeAsync(app.Services, app.Configuration, app.Logger);
app.MapAuthEndpoints();
app.Run();